#include "T117.h"

/* 设备地址定义 */
#define T117_WADD 0x80  /* 写地址 */
#define T117_RADD 0x81  /* 读地址 */

/*
 * 寄存器说明
 * -----------------------------------------------------------------------------
 * 转换指令寄存器：Temp_Cmd，寄存器地址 0x04
 * 配置寄存器：Temp_Cfg，寄存器地址 0x05
 * 状态寄存器：Status，寄存器地址 0x03
 * -----------------------------------------------------------------------------
 */

/* 状态寄存器（Status）位定义:
 * 位 | 功能描述                | 默认值
 * ---+------------------------+--------
 * 7  | 温度高阈值报警输出      | 0：温度报警未触发 1：温度报警已触发 '0'
 * 6  | 温度低阈值报警输出      | 0：温度报警未触发 1：温度报警已触发 '0'
 * 5  | 温度转换状态           | 0：温度转换完成 1：温度转换正在进行 '0'
 * 4  | E2PROM 状态           | 0：未处于读写状态 1：正在处于读写状态 '0'
 * 3  | 忙状态              | 0：未处于计算状态 1：正在处于计算状态 '0'
 * 2  | 温度报警溢出指示       | 0：TH 大于 TL 1：TH 小于等于 TL '0'
 * 1:0| 保留                  | '00'
 */

/* 报警模式寄存器（Alert_Mode），寄存器地址 0x06 */

/* 报警模式寄存器（Alert_Mode）位定义:
 * 位 | 功能描述                | 默认值
 * ---+------------------------+--------
 * 7  | 报警功能开关(Alert_en)  | 0：关闭 1：使能 '0'
 * 6  | 报警模式(IM)选择        | 0：迟滞TH高阈+迟滞TL低阈输出 1：窗口TH高阈+窗口TL低阈 '0'
 * 5  | 报警极性(POL)选择       | 0：低电平有效 1：高电平有效 '0'
 * 4  | 报警引脚输出模式(FUNC)  | 0：输出温度报警标志位 1：输出转换完成标志位 '0'
 * 3:0| 保留                   | '0000'
 */


/**
 * @brief  初始化T117温度传感器
 */
void T117_Init(void)
{
    MyI2C_Init();

    /* 设置转换指令寄存器，连续转换模式，正常功耗 */
    T117_W_REG(Temp_Cmd, 0x00);  /* 启动连续采样 */

    /* 设置配置寄存器
     * 0x39 = 0011 1001b
     * 位7-5: 001 - 每秒2次采样频率（对应FRE_2times）
     * 位4-3: 10 - 32次平均滤波（对应AVG_32）
     * 位0:   1 - 开启低功耗模式（对应ON_PD）
     */
    T117_W_REG(Temp_Cfg, 0x39);  /* 每秒2次，32次平均，开启低功耗 */

    /* 设置报警模式寄存器
     * 0x90 = 1001 0000b
     * 位7: 1 - 报警功能使能
     * 位4: 1 - 报警引脚输出转换完成标志位（对应CONVERT_FINI）
     */
    T117_W_REG(Alert_Mode, 0x90);  /* 使能报警，输出转换完成标志 */
}

/**
 * @brief  读取设备ID
 * @retval ID值，成功返回设备ID，失败返回错误码(1-3)
 */
uint8_t T117_ID(void)
{
    uint8_t temp = 0;

    /* 第1步：发送I2C起始信号 */
    MyI2C_Start();

    /* 第2步：发送设备写地址(0x80)，并等待应答 */
    MyI2C_SendByte(T117_WADD);
    temp = MyI2C_ReceiveAck();
    /* 检查应答，无应答则停止信号并返回错误码1 */
    if(temp) {MyI2C_Stop(); return 1;}

    /* 第3步：发送ROM代码2寄存器地址(0x19)，并等待应答 */
    MyI2C_SendByte(0x19);  /* Romcode2寄存器存储设备ID */
    temp = MyI2C_ReceiveAck();
    /* 检查应答，无应答则停止信号并返回错误码2 */
    if(temp) {MyI2C_Stop(); return 2;}

    /* 第4步：发送重复起始信号，准备读取数据 */
    MyI2C_Start();

    /* 第5步：发送设备读地址(0x81)，并等待应答 */
    MyI2C_SendByte(T117_RADD);
    temp = MyI2C_ReceiveAck();
    /* 检查应答，无应答则停止信号并返回错误码3 */
    if(temp) {MyI2C_Stop(); return 3;}

    /* 第6步：读取一个字节的ID数据 */
    temp = MyI2C_ReceiveByte();

    /* 第7步：发送非应答信号，表示不再读取 */
    MyI2C_SendAck(1);

    /* 第8步：发送停止信号，结束通信 */
    MyI2C_Stop();

    /* 返回读取到的ID值 */
    return temp;
}

/**
 * @brief  读取寄存器值
 * @param  REG: 寄存器地址
 * @param  DAT: 数据存储指针
 * @retval 0:成功 其他:错误代码
 *         1: 发送设备地址失败
 *         2: 发送寄存器地址失败
 *         3: 读取数据时设备无应答
 */
uint8_t T117_R_REG(uint8_t REG, uint8_t *DAT)
{
    uint8_t temp = 0;

    /* 第1步：发送I2C起始信号，开始通信 */
    MyI2C_Start();

    /* 第2步：发送设备写地址(0x80)，表示要写入数据 */
    MyI2C_SendByte(T117_WADD);
    temp = MyI2C_ReceiveAck();
    /* 检查应答信号，无应答则停止通信并返回错误码1 */
    if(temp) {MyI2C_Stop(); return 1;}

    /* 第3步：发送要读取的寄存器地址 */
    MyI2C_SendByte(REG);
    temp = MyI2C_ReceiveAck();
    /* 检查应答信号，无应答则停止通信并返回错误码2 */
    if(temp) {MyI2C_Stop(); return 2;}

    /* 第4步：发送重复起始信号，准备读取数据 */
    MyI2C_Start();

    /* 第5步：发送设备读地址(0x81)，表示要读取数据 */
    MyI2C_SendByte(T117_RADD);
    temp = MyI2C_ReceiveAck();
    /* 检查应答信号，无应答则停止通信并返回错误码3 */
    if(temp) {MyI2C_Stop(); return 3;}

    /* 第6步：读取寄存器数据并存储到指针指向的变量 */
    *DAT = MyI2C_ReceiveByte();

    /* 第7步：发送非应答信号，表示不再读取 */
    MyI2C_SendAck(1);

    /* 第8步：发送停止信号，结束通信 */
    MyI2C_Stop();

    /* 返回成功标志 */
    return 0;
}

/**
 * @brief  写寄存器值
 * @param  REG: 寄存器地址
 * @param  DAT: 要写入的数据
 * @retval 0:成功 其他:错误代码
 *         1: 发送设备地址失败
 *         2: 发送寄存器地址失败
 *         3: 发送数据失败
 */
uint8_t T117_W_REG(uint8_t REG, uint8_t DAT)
{
    uint8_t temp = 0;

    /* 第1步：发送I2C起始信号，开始通信 */
    MyI2C_Start();

    /* 第2步：发送设备写地址(0x80) */
    MyI2C_SendByte(T117_WADD);
    temp = MyI2C_ReceiveAck();
    /* 检查应答信号，无应答则停止通信并返回错误码1 */
    if(temp) {MyI2C_Stop(); return 1;}

    /* 第3步：发送要写入的寄存器地址 */
    MyI2C_SendByte(REG);
    temp = MyI2C_ReceiveAck();
    /* 检查应答信号，无应答则停止通信并返回错误码2 */
    if(temp) {MyI2C_Stop(); return 2;}

    /* 第4步：发送要写入的数据 */
    MyI2C_SendByte(DAT);
    temp = MyI2C_ReceiveAck();
    /* 检查应答信号，无应答则停止通信并返回错误码3 */
    if(temp) {MyI2C_Stop(); return 3;}

    /* 第5步：发送停止信号，结束通信 */
    MyI2C_Stop();

    /* 返回成功标志 */
    return 0;
}

/**
 * @brief  读取温度值
 * @param  DAT: 温度数据存储指针
 * @retval 0:成功 其他:错误代码
 *         1: 读取温度高字节失败
 *         2: 读取温度低字节失败
 */
uint8_t T117_R_TEMP(float *DAT)
{
    uint16_t rx = 0;     /* 用于存储合并后的16位温度原始数据 */
    uint8_t data = 0;    /* 临时存储每个字节的数据 */

    /* 第1步：读取温度高字节(MSB)，寄存器地址0x01 */
    if(T117_R_REG(0x01, &data)) return 1;
    rx = data;           /* 高字节数据传入rx */
    rx <<= 8;            /* 左移8位，为低字节预留位置 */

    /* 第2步：读取温度低字节(LSB)，寄存器地址0x00 */
    if(T117_R_REG(0x00, &data)) return 2;
    rx += data;          /* 低字节数据加入rx，完成16位温度数据拼接 */

    /* 第3步：将16位原始数据转换为有符号整数，以处理负温度 */
    *DAT = (int16_t)rx;

    /* 第4步：将原始数据转换为实际温度值（摄氏度）
     * 转换公式: 温度 = 25.0 + 原始数据 / 256.0
     * 说明: 25.0是基准温度，原始数据表示相对于25度的偏移量
     * 每1个数字量代表1/256摄氏度的温度变化
     */
    *DAT = 25.0 + (*DAT) / 256.0;

    /* 返回成功标志 */
    return 0;
}
